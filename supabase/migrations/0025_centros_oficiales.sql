-- Paso 2 de la unificación (17-11-2026): lista oficial de centros, compartida por la app de guías y el buscador.
-- Cada forma de escribir el contacto de una guía (normalizada: mayúsculas, sin tildes ni signos) dice a qué centro va.
-- tipo: centro = cuenta como venta en su centro; otros = cuenta, en «Otros» de la empresa;
--       bins = transporte de bins (no es venta); fuera = no cuenta (error, decidido por Hugo).
-- Aplicada el 17-11-2026, con las decisiones de Hugo de ese día (89 filas, abajo).
create table if not exists public.centros (
  id bigserial primary key,
  customer_id bigint not null,
  contacto text not null,
  centro text not null,
  tipo text not null default 'centro' check (tipo in ('centro', 'otros', 'bins', 'fuera')),
  revisado boolean not null default true,
  nota text,
  creado_en timestamptz not null default now(),
  unique (customer_id, contacto)
);
alter table public.centros enable row level security;
grant select (customer_id, contacto, centro, tipo, revisado) on public.centros to lector_buscador;
create policy lector_buscador_lee on public.centros for select to lector_buscador using (true);
grant select (nombre, codigo_interno, relbase_customer_id) on public.empresas to lector_buscador;
create policy lector_buscador_lee on public.empresas for select to lector_buscador using (true);

